"""Independent, non-production specification calculator; uses hashlib SHAKE.

Only this explicit --write command updates committed known-answer vectors.
Normal checks recompute them and fail on any specification/vector drift.
"""

import argparse
import hashlib
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
SBOX = (12, 5, 6, 11, 9, 0, 10, 13, 3, 14, 15, 8, 4, 7, 1, 2)
MASK = (1 << 32) - 1


def rol(x, n):
    n %= 32
    return ((x << n) | (x >> ((32 - n) % 32))) & MASK


def substitution(x):
    return sum(SBOX[(x >> (4 * i)) & 15] << (4 * i) for i in range(8))


def linear(x):
    return x ^ rol(x, 3) ^ rol(x, 17)


def fs(x, key):
    return linear(substitution(x ^ key))


def fm(x, key):
    y = substitution(x ^ key)
    sum1 = (y + rol(key, 9)) & MASK
    rotated = rol(y ^ key, 7)
    w = rol((sum1 + rotated) & MASK, 11) ^ rol(y & rol(key, 3), 19)
    return linear(substitution(w ^ rol(key, 13)))


def schedule(key):
    if len(key) != 32:
        raise ValueError("key must be 32 bytes")
    words = struct.unpack("<112I", hashlib.shake_256(
        b"Interlock-128/roundkeys\x00" + key).digest(448))
    return [words[i:i + 4] for i in range(0, 112, 4)]


def forward(state, key):
    a, b, c, d = state
    new_a = a ^ fs(b, key[0])
    new_c = c ^ fm(d, key[1])
    new_b = b ^ fm(new_c, key[2])
    new_d = d ^ fs(new_a, key[3])
    return (rol(new_c, 5), rol(new_a, 13), rol(new_d, 21), rol(new_b, 27))


def backward(state, key):
    # Graph reversal: undo output wiring, then reverse the four XOR edges.
    s = [rol(state[1], -13), rol(state[3], -27),
         rol(state[0], -5), rol(state[2], -21)]
    for dst, src, ki, function in ((3, 0, 3, fs), (1, 2, 2, fm),
                                   (2, 3, 1, fm), (0, 1, 0, fs)):
        s[dst] ^= function(s[src], key[ki])
    return tuple(s)


def trace(key, plaintext):
    if len(plaintext) != 16:
        raise ValueError("block must be 16 bytes")
    keys = schedule(key)
    states = [struct.unpack("<4I", plaintext)]
    for k in keys:
        states.append(forward(states[-1], k))
    return keys, states, struct.pack("<4I", *states[-1])


def cases():
    return [(bytes(32), bytes(16)), (b"\xff" * 32, b"\xff" * 16),
            (bytes(range(32)), bytes(range(16))), (b"\xaa\x55" * 16, b"\x80\x01" * 8)]


def vector_header():
    fingerprint = hashlib.sha256((ROOT / "docs/spec_ko.md").read_bytes()).hexdigest()
    lines = ["/* Generated by tests/reference.py --write; independent of the C core. */",
             "#ifndef INTERLOCK_KAT_VECTORS_H", "#define INTERLOCK_KAT_VECTORS_H",
             "#include <stdint.h>", f'#define KAT_SPEC_SHA256 "{fingerprint}"',
             "static const struct {", "    uint8_t key[32], plaintext[16], ciphertext[16];",
             "    uint32_t keys[28][4], states[29][4];", "} kat_vectors[] = {"]
    for key, plaintext in cases():
        keys, states, ciphertext = trace(key, plaintext)
        lines.append("    {")
        for data in (key, plaintext, ciphertext):
            lines.append("        {" + ",".join(f"0x{v:02x}" for v in data) + "},")
        for data in (keys, states):
            lines.append("        {")
            for row in data:
                lines.append("            {" + ",".join(f"UINT32_C(0x{v:08x})" for v in row) + "},")
            lines.append("        },")
        lines.append("    },")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="explicitly replace KAT after review")
    args = parser.parse_args()
    path = ROOT / "tests/vectors.h"
    expected = vector_header()
    if args.write:
        path.write_text(expected, encoding="utf-8")
        print("Wrote independently calculated tests/vectors.h")
    elif not path.exists() or path.read_text(encoding="utf-8") != expected:
        raise SystemExit("Specification/KAT mismatch: review changes before explicit --write")
    else:
        print("Independent KAT regeneration and specification SHA-256 match")


if __name__ == "__main__":
    main()
